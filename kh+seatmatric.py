import pandas as pd
import tabula
from pathlib import Path
import warnings
warnings.filterwarnings('ignore')

def detect_pdf_type(pdf_path):
    """
    Detect if PDF is MBBS or Dental based on filename or content
    """
    filename = Path(pdf_path).name.lower()

    if 'dental' in filename or 'bds' in filename:
        return 'DENTAL'
    elif 'mbbs' in filename or 'medical' in filename:
        return 'MBBS'
    else:
        # Try to detect from first page content
        try:
            first_page = tabula.read_pdf(pdf_path, pages='1', multiple_tables=True)
            if first_page:
                text = str(first_page[0]).lower()
                if 'dental' in text or 'bds' in text:
                    return 'DENTAL'
                elif 'mbbs' in text or 'medical' in text:
                    return 'MBBS'
        except:
            pass

    return 'UNKNOWN'

def get_total_pages(pdf_path):
    """
    Get total number of pages in PDF
    """
    try:
        import PyPDF2
        with open(pdf_path, 'rb') as file:
            pdf_reader = PyPDF2.PdfReader(file)
            return len(pdf_reader.pages)
    except:
        return None

def extract_tables_smart(pdf_path, pdf_type):
    """
    Extract tables with smart page handling
    """
    total_pages = get_total_pages(pdf_path)

    if total_pages:
        print(f"📄 Total pages in PDF: {total_pages}")

    all_tables = []

    # Extract page by page for better control
    pages_to_extract = total_pages if total_pages else 10  # fallback to 10 if can't detect

    for page_num in range(1, min(pages_to_extract + 1, 20)):  # Max 20 pages
        try:
            print(f"  Extracting page {page_num}...", end=" ")

            # Try lattice mode first (better for structured tables)
            tables = tabula.read_pdf(
                pdf_path,
                pages=str(page_num),
                multiple_tables=True,
                lattice=True,
                pandas_options={'header': None}
            )

            if tables and len(tables) > 0:
                for table in tables:
                    if not table.empty and table.shape[0] > 2:  # Only keep non-empty tables
                        all_tables.append({
                            'page': page_num,
                            'data': table
                        })
                print(f"✓ Found {len(tables)} table(s)")
            else:
                # Try stream mode if lattice fails
                tables = tabula.read_pdf(
                    pdf_path,
                    pages=str(page_num),
                    multiple_tables=True,
                    stream=True,
                    pandas_options={'header': None}
                )

                if tables and len(tables) > 0:
                    for table in tables:
                        if not table.empty and table.shape[0] > 2:
                            all_tables.append({
                                'page': page_num,
                                'data': table
                            })
                    print(f"✓ Found {len(tables)} table(s) (stream mode)")
                else:
                    print("⚠ No tables found")

        except Exception as e:
            print(f"✗ Error: {str(e)[:50]}")
            continue

    return all_tables

def clean_dataframe(df):
    """
    Clean and standardize the dataframe
    """
    # Remove completely empty rows
    df = df.dropna(how='all')

    # Remove rows where all values are empty strings
    df = df[~df.apply(lambda x: x.astype(str).str.strip().eq('').all(), axis=1)]

    # Reset index
    df = df.reset_index(drop=True)

    return df

def save_to_excel(all_tables, output_path, pdf_type):
    """
    Save all extracted tables to a single Excel file
    """
    with pd.ExcelWriter(output_path, engine='openpyxl') as writer:

        # Group tables by page
        pages = {}
        for item in all_tables:
            page_num = item['page']
            if page_num not in pages:
                pages[page_num] = []
            pages[page_num].append(item['data'])

        # Save each page's tables
        for page_num in sorted(pages.keys()):
            tables = pages[page_num]

            for idx, table in enumerate(tables):
                cleaned_table = clean_dataframe(table)

                if not cleaned_table.empty:
                    sheet_name = f'Page_{page_num}_Table_{idx+1}'
                    # Excel sheet names max 31 characters
                    sheet_name = sheet_name[:31]

                    cleaned_table.to_excel(writer, sheet_name=sheet_name, index=False, header=False)
                    print(f"  ✓ Saved {sheet_name}: {cleaned_table.shape[0]} rows × {cleaned_table.shape[1]} cols")

        # Create combined sheets by page
        for page_num in sorted(pages.keys()):
            try:
                tables = pages[page_num]

                # Find most common column count
                col_counts = [t.shape[1] for t in tables]
                if col_counts:
                    most_common_cols = max(set(col_counts), key=col_counts.count)

                    # Combine tables with same column count
                    compatible = [t for t in tables if t.shape[1] == most_common_cols]

                    if compatible:
                        combined = pd.concat(compatible, ignore_index=True)
                        combined = clean_dataframe(combined)

                        sheet_name = f'Page_{page_num}_Combined'[:31]
                        combined.to_excel(writer, sheet_name=sheet_name, index=False, header=False)
                        print(f"  ✓ Saved {sheet_name}: {combined.shape[0]} rows × {combined.shape[1]} cols")
            except Exception as e:
                print(f"  ⚠ Could not create combined sheet for page {page_num}")

        # Try to create master combined sheet
        try:
            all_data_tables = [item['data'] for item in all_tables]
            col_counts = [t.shape[1] for t in all_data_tables]

            if col_counts:
                most_common_cols = max(set(col_counts), key=col_counts.count)
                compatible = [t for t in all_data_tables if t.shape[1] == most_common_cols]

                if compatible:
                    master = pd.concat(compatible, ignore_index=True)
                    master = clean_dataframe(master)

                    master.to_excel(writer, sheet_name='All_Data_Combined', index=False, header=False)
                    print(f"\n  ✓ Saved All_Data_Combined: {master.shape[0]} rows × {master.shape[1]} cols")
        except Exception as e:
            print(f"  ⚠ Could not create master combined sheet")

