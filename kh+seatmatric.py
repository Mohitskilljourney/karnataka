    if tables_p1_3 is None and tables_p4 is None:
        print("❌ Failed to extract any tables. Trying alternate method...")

        # Try alternate extraction
        tables_p1_3 = extract_with_alternate_method(pdf_path, '1-3')
        tables_p4 = extract_with_alternate_method(pdf_path, '4')

    # Prepare Excel writer
    output_excel = pdf_path.stem + '_extracted.xlsx'

    with pd.ExcelWriter(output_excel, engine='openpyxl') as writer:
        sheet_number = 1

        # Process pages 1-3
        if tables_p1_3:
            print(f"\n📊 Found {len(tables_p1_3)} tables in pages 1-3")
            merged_p1_3 = merge_tables(tables_p1_3)

            if merged_p1_3:
                for i, table in enumerate(merged_p1_3):
                    sheet_name = f'Pages_1-3_Table_{i+1}'
                    table.to_excel(writer, sheet_name=sheet_name, index=False, header=False)
                    print(f"  ✓ Saved {sheet_name}: {table.shape[0]} rows × {table.shape[1]} columns")
                    sheet_number += 1

                # Also save combined pages 1-3
                combined_p1_3 = pd.concat(merged_p1_3, ignore_index=True)
                combined_p1_3.to_excel(writer, sheet_name='Pages_1-3_Combined', index=False, header=False)
                print(f"  ✓ Saved Pages_1-3_Combined: {combined_p1_3.shape[0]} rows × {combined_p1_3.shape[1]} columns")

        # Process page 4 separately
        if tables_p4:
            print(f"\n📊 Found {len(tables_p4)} tables in page 4")
            merged_p4 = merge_tables(tables_p4)

            if merged_p4:
                for i, table in enumerate(merged_p4):
                    sheet_name = f'Page_4_Table_{i+1}'
                    table.to_excel(writer, sheet_name=sheet_name, index=False, header=False)
                    print(f"  ✓ Saved {sheet_name}: {table.shape[0]} rows × {table.shape[1]} columns")
                    sheet_number += 1

                # Also save combined page 4
                combined_p4 = pd.concat(merged_p4, ignore_index=True)
                combined_p4.to_excel(writer, sheet_name='Page_4_Combined', index=False, header=False)
                print(f"  ✓ Saved Page_4_Combined: {combined_p4.shape[0]} rows × {combined_p4.shape[1]} columns")

        # Try to create a master sheet with all data
        try:
            all_tables = []
            if tables_p1_3:
                all_tables.extend(tables_p1_3)
            if tables_p4:
                all_tables.extend(tables_p4)

            if all_tables:
                # Find the most common column count
                col_counts = [t.shape[1] for t in all_tables]
                most_common_cols = max(set(col_counts), key=col_counts.count)

                # Only combine tables with the same column count
                compatible_tables = [t for t in all_tables if t.shape[1] == most_common_cols]

                if compatible_tables:
                    master_df = pd.concat(compatible_tables, ignore_index=True)
                    master_df = clean_dataframe(master_df)
                    master_df.to_excel(writer, sheet_name='All_Data_Combined', index=False, header=False)
                    print(f"\n  ✓ Saved All_Data_Combined: {master_df.shape[0]} rows × {master_df.shape[1]} columns")
        except Exception as e:
            print(f"  ⚠ Could not create combined sheet: {e}")

    print(f"\n{'='*60}")
    print(f"✅ Extraction complete!")
    print(f"📁 Output saved to: {output_excel}")
    print(f"{'='*60}\n")

